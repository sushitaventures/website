/**
 * Website image pipeline (manifest: scripts/image-manifest.mjs).
 *
 *   npm run images -- import    Import generated images from client/image-drop/<id>.(png|jpg|jpeg|webp):
 *                               crop to the exact size (attention-based focal point), write every
 *                               output format, mark them replaced, refresh the inventory.
 *   npm run images -- standins  Create missing new files (service heroes, asset cards) from a related
 *                               existing photo so nothing renders broken before generation.
 *   npm run images -- sheet     Rewrite docs/IMAGE_INVENTORY.md (inventory + prompt sheet) only.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { IMAGES, KEPT, STYLE } from './image-manifest.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pub = path.join(root, 'public', 'images');
const drop = path.join(root, 'image-drop');
const ledgerFile = path.join(root, 'scripts', 'image-status.json');
const sheetFile = path.join(root, '..', 'docs', 'IMAGE_INVENTORY.md');

const ledger = fs.existsSync(ledgerFile) ? JSON.parse(fs.readFileSync(ledgerFile, 'utf8')) : {};
const outPath = (img, suffix) => path.join(pub, `${img.id}${suffix}`);
const webPath = (img, suffix) => `/images/${img.id}${suffix}`;

// sharp keeps only the last resize() in a pipeline, so each output gets its own crop
const crop = (source, w, h) => sharp(source).rotate().resize(w, h, { fit: 'cover', position: sharp.strategy.attention });

const writeAll = async (img, source) => {
  for (const suffix of img.outputs) {
    const file = outPath(img, suffix);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const p = suffix === '-640.webp' ? crop(source, 640, Math.round((640 * img.h) / img.w)) : crop(source, img.w, img.h);
    if (suffix === '-640.webp') await p.webp({ quality: 72, effort: 6 }).toFile(file);
    else if (suffix === '.webp') await p.webp({ quality: 78, effort: 6 }).toFile(file);
    else await p.jpeg({ quality: 80, mozjpeg: true, progressive: true }).toFile(file);
  }
};

const cmd = process.argv[2] || 'sheet';

if (cmd === 'import') {
  let n = 0;
  for (const img of IMAGES) {
    const src = ['.png', '.jpg', '.jpeg', '.webp'].map((e) => path.join(drop, img.id + e)).find((f) => fs.existsSync(f));
    if (!src) continue;
    await writeAll(img, src);
    ledger[img.id] = new Date().toISOString().slice(0, 10);
    console.log(`imported  ${img.id}  →  ${img.outputs.map((s) => webPath(img, s)).join(', ')}`);
    n++;
  }
  fs.writeFileSync(ledgerFile, JSON.stringify(ledger, null, 2) + '\n');
  console.log(`\n${n} image(s) imported; ${IMAGES.filter((i) => !ledger[i.id]).length} still pending.`);
}

if (cmd === 'standins') {
  for (const img of IMAGES.filter((i) => i.standIn)) {
    if (img.outputs.every((s) => fs.existsSync(outPath(img, s)))) continue;
    await writeAll(img, path.join(pub, img.standIn));
    console.log(`stand-in  ${img.id}  ←  ${img.standIn}`);
  }
}

// Inventory + prompt sheet (always refreshed)
const status = (img) => (ledger[img.id] ? `Replaced (${ledger[img.id]})` : img.standIn ? 'Pending — stand-in shown' : 'Pending');
const rows = IMAGES.map(
  (img) =>
    `| ${img.page} — ${img.section} | ${img.standIn ? `new (stand-in: \`${img.standIn}\`)` : `\`${img.id}${img.outputs[0] === '.jpg' ? '.jpg' : '.*'}\``} | \`image-drop/${img.id}.png\` → ${img.outputs.map((s) => `\`${webPath(img, s)}\``).join(', ')} | ${img.w}×${img.h} | ${status(img)} |`
);
const used = new Set(IMAGES.flatMap((i) => [...i.outputs.map((s) => `${i.id}${s}`), i.standIn]).concat(KEPT.map((k) => k[0])));
const unused = [];
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
for (const f of walk(pub)) {
  const rel = path.relative(pub, f).split(path.sep).join('/');
  if (!used.has(rel) && !/\/assets\/|\/hero\.webp$/.test(rel)) unused.push(rel);
}
const pending = IMAGES.filter((i) => !ledger[i.id]).length;

fs.writeFileSync(
  sheetFile,
  `# Website image inventory & prompt sheet

Generated by \`client/scripts/image-assets.mjs\` from \`client/scripts/image-manifest.mjs\` — edit prompts there, then re-run.
**${IMAGES.length - pending} of ${IMAGES.length} replaced, ${pending} pending.**

## How to replace an image

1. Generate it with the prompt below (any tool). Aim for at least the listed size, roughly the same shape.
2. Save it as \`client/image-drop/<id>.png\` (or .jpg/.webp) — e.g. \`client/image-drop/home/hero-commercial.png\`.
3. Run \`npm run images -- import\` in \`client/\`. It crops to the exact size, writes WebP/JPEG and phone variants, and updates this file.
4. \`npm run build\`, check the page, commit \`client/public/images\` + \`client/scripts/image-status.json\`. (\`image-drop/\` is git-ignored.)

**Style suffix — append to every prompt:**
> ${STYLE}

## Inventory

| Page / Section | Existing image | Replacement (drop → output) | Size | Status |
|---|---|---|---|---|
${rows.join('\n')}

### Reviewed, intentionally not regenerated
${KEPT.map(([p, why]) => `- \`${p}\` — ${why}`).join('\n')}

### Not used anywhere on the site (safe to delete once stand-ins are replaced)
${unused.sort().map((p) => `- \`${p}\``).join('\n')}

## Prompts

${IMAGES.map((img) => `### \`${img.id}\` — ${img.w}×${img.h}\n${img.page} · ${img.section}\n\n> ${img.prompt}\n`).join('\n')}`
);
console.log(`inventory → docs/IMAGE_INVENTORY.md (${pending}/${IMAGES.length} pending)`);
